export function extractTagsFromText(title: string, desc: string): string[] {
  const t = (title + ' ' + desc).toLowerCase();
  const matched: string[] = [];

  if (t.includes('mac') || t.includes('macos') || t.includes('swiftui') || t.includes('apple')) matched.push('mac');
  if (t.includes('ai') || t.includes('model') || t.includes('intelligence') || t.includes('assistant') || t.includes('gpt')) matched.push('ai');
  if (t.includes('open-source') || t.includes('open source') || t.includes('github') || t.includes('rust') || t.includes('v language')) matched.push('open-source');
  if (t.includes('productivity') || t.includes('kanban') || t.includes('tabs') || t.includes('pomodoro') || t.includes('task') || t.includes('organize')) matched.push('productivity');
  if (t.includes('browser') || t.includes('webkit') || t.includes('tabs')) matched.push('browser');
  if (t.includes('privacy') || t.includes('secrets') || t.includes('encrypted') || t.includes('vault') || t.includes('blocking')) matched.push('security');
  if (t.includes('database') || t.includes('cli') || t.includes('terminal') || t.includes('cad') || t.includes('query') || t.includes('react')) matched.push('developer');
  if (t.includes('audio') || t.includes('bass') || t.includes('player') || t.includes('music') || t.includes('sound')) matched.push('audio');

  if (matched.length === 0) matched.push('developer');
  return Array.from(new Set(matched));
}

export function parseAlternativeToXml(xmlString: string = DEFAULT_ALTERNATIVE_TO_XML): {
  feed: FeedSource;
  items: FeedItem[];
} {
  const parser = new DOMParser();
  const xmlDoc = parser.parseFromString(xmlString, 'text/xml');
  const channel = xmlDoc.querySelector('channel');

  const feedTitle = channel?.querySelector('title')?.textContent || 'New Releases – AlternativeTo.net';
  const feedLink = channel?.querySelector('link')?.textContent || 'https://alternativeto.net/browse/new-apps/';
  const feedDesc = channel?.querySelector('description')?.textContent || 'The latest software added to AlternativeTo';
  const feedIcon = channel?.querySelector('image > url')?.textContent || 'https://alternativeto.net/favicon.png';

  const feed: FeedSource = {
    id: 'alternativeto-new',
    title: feedTitle,
    url: 'https://alternativeto.net/browse/new-apps/feed/',
    link: feedLink,
    description: feedDesc,
    category: 'software',
    icon: feedIcon,
    color: '#6366f1',
    lastFetched: Date.now(),
    isDefault: true,
    customTags: ['software', 'mac', 'tools', 'free'],
    syncStatus: 'success',
  };

  const itemNodes = xmlDoc.querySelectorAll('item');
  const items: FeedItem[] = [];

  itemNodes.forEach((node, index) => {
    const title = node.querySelector('title')?.textContent || 'Untitled Release';
    const link = node.querySelector('link')?.textContent || '';
    const guid = node.querySelector('guid')?.textContent || link || `alt-${index}`;
    const pubDateStr = node.querySelector('pubDate')?.textContent || new Date(Date.now() - index * 86400000).toUTCString();
    const descRaw = node.querySelector('description')?.textContent || '';
    const enclosureNode = node.querySelector('enclosure');
    
    let enclosureUrl = enclosureNode?.getAttribute('url') || '';
    const enclosureType = enclosureNode?.getAttribute('type') || 'image/jpeg';
    
    // Clean description HTML and extract links
    const tempDiv = document.createElement('div');
    tempDiv.innerHTML = descRaw;
    const cleanText = tempDiv.textContent || tempDiv.innerText || '';
    
    // Extract image if enclosure is not present
    if (!enclosureUrl) {
      const imgInDesc = tempDiv.querySelector('img')?.getAttribute('src');
      if (imgInDesc) enclosureUrl = imgInDesc;
    }

    const tags = extractTagsFromText(title, cleanText);
    const wordCount = (title + ' ' + cleanText).split(/\s+/).filter(Boolean).length;
    const readingTime = Math.max(1, Math.ceil(wordCount / 180));

    // Media type detection
    let mediaType: 'video' | 'audio' | 'image' | 'article' = 'image';
    let videoUrl = '';
    let audioUrl = '';

    if (title.toLowerCase().includes('player') || title.toLowerCase().includes('sonexis') || title.toLowerCase().includes('chirpy')) {
      // Demo audio capability
      audioUrl = 'https://actions.google.com/sounds/v1/ambiences/rain_heavy.ogg';
      mediaType = 'audio';
    }

    if (title.toLowerCase().includes('lumae') || title.toLowerCase().includes('owlcad')) {
      // Demo video capability
      videoUrl = 'https://commondatastorage.googleapis.com/gtv-videos-bucket/sample/ForBiggerBlazes.mp4';
      mediaType = 'video';
    }

    items.push({
      id: `item-alt-${index}-${guid.replace(/[^a-zA-Z0-9]/g, '')}`,
      guid: guid,
      title: title,
      link: link,
      pubDate: pubDateStr,
      isoDate: new Date(pubDateStr).toISOString(),
      timestamp: new Date(pubDateStr).getTime() || (Date.now() - index * 3600000 * 6),
      description: cleanText,
      content: descRaw,
      author: 'AlternativeTo.net',
      enclosure: enclosureUrl ? {
        url: enclosureUrl,
        type: enclosureType,
      } : undefined,
      imageUrl: enclosureUrl,
      videoUrl: videoUrl,
      audioUrl: audioUrl,
      mediaType: mediaType,
      category: 'software',
      tags: tags,
      feedId: feed.id,
      feedTitle: feed.title,
      feedIcon: feed.icon,
      isFavorite: index === 0 || index === 2, // Mark a couple as sample favorites
      isReadLater: index === 1,
      isRead: false,
      readingTimeMinutes: readingTime,
      wordCount: wordCount,
      cachedOffline: true,
      aiSummary: `${title} is a specialized app added to AlternativeTo. Key highlights: ${cleanText.slice(0, 140)}...`,
      aiKeyTakeaways: [
        `Direct download and review available on AlternativeTo`,
        `Tagged under: ${tags.join(', ')}`,
        `Designed for modern user workflows and native system integration`
      ],
      aiSentiment: 'positive',
    });
  });

  feed.itemCount = items.length;
  feed.unreadCount = items.length;

  return { feed, items };
}
